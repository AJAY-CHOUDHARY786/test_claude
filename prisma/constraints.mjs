export function renderPostgresSql() {
  const lines = ["-- Generated by scripts/render-constraints.mjs from prisma/constraints.mjs. Safe to run repeatedly.", "-- Apply with: npm run db:constraints (after prisma migrate).", ""];
  for (const c of CONSTRAINTS) {
    lines.push(`ALTER TABLE "${c.table}" DROP CONSTRAINT IF EXISTS "${c.name}";`);
    lines.push(`ALTER TABLE "${c.table}" ADD CONSTRAINT "${c.name}" CHECK (${c.check});`);
  }
  lines.push("");
  for (const i of INDEXES) lines.push(`${i.sql};`);
  return lines.join("\n") + "\n";
}
